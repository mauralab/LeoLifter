CREATE TABLE IF NOT EXISTS languages (
    id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
    code varchar(35) NOT NULL,
    native_name varchar(100) NOT NULL,
    CONSTRAINT language_code_check CHECK (code ~ '^[a-z]{2,3}(-[a-z0-9]{2,8})*$'),
    CONSTRAINT language_native_name_check CHECK (native_name = btrim(native_name) AND native_name <> '')
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_languages_code ON languages(code);
