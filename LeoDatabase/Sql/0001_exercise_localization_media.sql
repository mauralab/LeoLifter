CREATE TABLE IF NOT EXISTS exercise_translations (
    exercise_id bigint NOT NULL REFERENCES exercises(id) ON DELETE CASCADE,
    language_id bigint NOT NULL REFERENCES languages(id) ON DELETE RESTRICT,
    title text NOT NULL,
    description text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (exercise_id, language_id),
    CONSTRAINT exercise_translation_title_check CHECK (title = btrim(title) AND title <> '')
);
CREATE INDEX IF NOT EXISTS ix_exercise_translations_language_id ON exercise_translations(language_id);
CREATE TABLE IF NOT EXISTS exercise_media (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exercise_id bigint NOT NULL REFERENCES exercises(id) ON DELETE CASCADE,
    type exercise_media_type NOT NULL,
    position integer NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT exercise_media_position_check CHECK (position >= 1)
);
CREATE UNIQUE INDEX IF NOT EXISTS ix_exercise_media_exercise_id_position ON exercise_media(exercise_id, position);
CREATE TABLE IF NOT EXISTS exercise_media_translations (
    exercise_media_id bigint NOT NULL REFERENCES exercise_media(id) ON DELETE CASCADE,
    language_id bigint NOT NULL REFERENCES languages(id) ON DELETE RESTRICT,
    url varchar(2048) NOT NULL,
    title text,
    description text,
    alt_text text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (exercise_media_id, language_id),
    CONSTRAINT exercise_media_url_check CHECK (url = btrim(url) AND url <> '')
);
CREATE INDEX IF NOT EXISTS ix_exercise_media_translations_language_id ON exercise_media_translations(language_id);
